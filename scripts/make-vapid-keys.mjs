/**
 * Make the VAPID key pair.
 *
 * VAPID (RFC 8292) is how a push server says "this notification is
 * from me". It is a P-256 ECDSA key pair: the public key goes to the
 * browser in `applicationServerKey`, the private key signs the request
 * the server makes to the push service.
 *
 * The keys are written to .dev.vars for local development. For a
 * deployment, put the same three values in with:
 *
 *   npx wrangler secret put VAPID_PUBLIC_KEY
 *   npx wrangler secret put VAPID_PRIVATE_KEY
 *   npx wrangler secret put VAPID_SUBJECT
 *
 * Losing the private key means every existing subscription has to be
 * re-created: the browser's subscription is bound to the public key it
 * was given.
 *
 * Run: node scripts/make-vapid-keys.mjs
 */
import { webcrypto } from "node:crypto";
import { writeFileSync, existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const b64url = (buf) =>
  Buffer.from(buf).toString("base64").replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");

const { publicKey, privateKey } = await webcrypto.subtle.generateKey(
  { name: "ECDSA", namedCurve: "P-256" },
  true,
  ["sign", "verify"]
);

const privJwk = await webcrypto.subtle.exportKey("jwk", privateKey);
const pubJwk = await webcrypto.subtle.exportKey("jwk", publicKey);

// The uncompressed point: 0x04 || X || Y, base64url. This is what
// applicationServerKey must be.
const x = Buffer.from(pubJwk.x, "base64url");
const y = Buffer.from(pubJwk.y, "base64url");
const uncompressed = Buffer.concat([Buffer.from([0x04]), x, y]);

const VAPID_PUBLIC_KEY = b64url(uncompressed);
const VAPID_PRIVATE_KEY = JSON.stringify(privJwk);
const VAPID_SUBJECT = "mailto:admin@taskmaster.local";

const varsPath = join(root, ".dev.vars");
let existing = "";
if (existsSync(varsPath)) {
  existing = readFileSync(varsPath, "utf8")
    .split("\n")
    .filter((line) => !/^VAPID_/.test(line.trim()))
    .join("\n")
    .replace(/\s+$/, "");
}

const block = [
  "",
  "# Web push (VAPID). Generated by scripts/make-vapid-keys.mjs",
  `VAPID_PUBLIC_KEY="${VAPID_PUBLIC_KEY}"`,
  `VAPID_PRIVATE_KEY='${VAPID_PRIVATE_KEY}'`,
  `VAPID_SUBJECT="${VAPID_SUBJECT}"`,
  "",
].join("\n");

writeFileSync(varsPath, (existing ? existing + "\n" : "") + block, "utf8");

console.log("VAPID keys written to .dev.vars");
console.log("  public key  ", VAPID_PUBLIC_KEY);
console.log("  subject     ", VAPID_SUBJECT);
console.log("");
console.log("For a deployment: npx wrangler secret put VAPID_PUBLIC_KEY (and the other two).");
